def normalize(lang):
    """把任意形式的语言标识归一为受支持的短码。"""
    if not lang:
        return DEFAULT_LANG
    lang = str(lang).strip().lower().replace("-", "_")
    short = lang.split("_")[0]
    return short if short in LANGS else DEFAULT_LANG


def get(lang):
    return DICT.get(normalize(lang), DICT[DEFAULT_LANG])


def langs_meta():
    return [{"code": c, "name": LANG_NAMES.get(c, c)} for c in LANGS]